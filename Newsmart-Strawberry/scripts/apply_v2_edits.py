def set_text(p, text):
    """保留段落样式，替换文本（保留第一个 run 的 rPr，删除其余 run）"""
    if p.runs:
        p.runs[0].text = text
        for r in p.runs[1:]:
            r._r.getparent().remove(r._r)
    else:
        p.add_run(text)


def insert_after(anchor, text):
    """在锚点段落后插入新段落，样式复制锚点段落"""
    new_el = copy.deepcopy(anchor._p)
    anchor._p.addnext(new_el)
    np = Paragraph(new_el, anchor._parent)
    set_text(np, text)
    return np


def insert_many_after(anchor, texts):
    """在锚点后按顺序插入多段，返回最后一段（便于链式）"""
    cur = anchor
    for t in texts:
        cur = insert_after(cur, t)
    return cur


def delete_para(p):
    p._p.getparent().remove(p._p)


